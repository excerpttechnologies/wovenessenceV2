function sheetRows(fields, data, requiredKeys = []) {
  return [
    [{ v: 'Test workbook', s: STYLE.TITLE }],
    [{ v: 'Generated by testBarcodeMasterImport.mjs', s: STYLE.NOTE }],
    fields.map((field) => ({
      v: field.label + (requiredKeys.includes(field.key) ? ' *' : ''),
      s: requiredKeys.includes(field.key) ? STYLE.HEADER_REQUIRED : STYLE.HEADER,
    })),
    ...data.map((values) => fields.map((field) => {
      const value = values[field.key];
      if (value === undefined || value === null || value === '') return null;
      return { v: value, s: field.style ? STYLE[field.style] : STYLE.DEFAULT };
    })),
  ];
}

function testWorkbook({ barcodes = [], masters = [] } = {}) {
  return buildXlsx({
    title: 'Barcode + Master Data import test',
    sheets: [
      {
        name: SHEET_NAMES.BARCODE,
        rows: sheetRows(BARCODE_FIELDS, barcodes, ['barcodeNo', 'itemCode', 'openingQty']),
        freeze: { row: 3 },
      },
      {
        name: SHEET_NAMES.MASTER,
        rows: sheetRows(MASTER_FIELDS, masters, ['masterType']),
        freeze: { row: 3 },
      },
    ],
  });
}

async function upload(ctx, { barcodes = [], masters = [], scope = IMPORT_SCOPES.BARCODE_MASTER, fileName = 'test.xlsx' } = {}) {
  const buffer = testWorkbook({ barcodes, masters });
  const { token, analysis } = await createSessionFromWorkbook({
    buffer,
    fileName,
    scope,
    businessId: String(ctx.business._id),
    locationId: String(ctx.location._id),
    finYear: FIN_YEAR,
    user: USER,
  });
  ctx.tokens.push(token);
  return { token, analysis, buffer };
}

