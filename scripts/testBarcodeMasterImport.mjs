function barcodeRow(ctx, barcodeNo) {
  return BarcodeLabel.findOne({ businessId: String(ctx.business._id), barcodeNo }).lean();
}

function movementRows(barcode) {
  return StockMovement.find({ barcodeId: barcode._id }).sort({ createdAt: 1 }).lean();
}

function workbookRows(buffer, sheetName) {
  const workbook = XLSX.read(buffer, { type: 'buffer', cellDates: true });
  return XLSX.utils.sheet_to_json(workbook.Sheets[sheetName], {
    header: 1,
    raw: false,
    defval: '',
  });
}

