function SelectExistingMasterDialog({ token, business, entry, onClose, onSaved }) {
  const [query, setQuery] = useState('');
  const [rows, setRows] = useState(() => (
    Array.isArray(entry?.candidates) ? entry.candidates : []
  ));
  const [searched, setSearched] = useState(Boolean(entry?.candidates?.length));
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');

  async function search(nextQuery = query) {
    setBusy(true);
    setError('');
    try {
      const params = new URLSearchParams({
        business,
        type: entry.type,
        q: nextQuery,
        limit: '40',
      });
      const response = await fetch(`/api/barcode-import/masters?${params.toString()}`);
      const data = await response.json().catch(() => ({}));
      if (!response.ok) throw new Error(data.error || `The ${entry.type} list could not be loaded.`);
      setRows(Array.isArray(data.masters) ? data.masters : []);
      setSearched(true);
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  }

  async function choose(master) {
    setBusy(true);
    setError('');
    try {
      const response = await fetch('/api/barcode-import/masters', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          token,
          mappings: [{
            type: entry.type,
            masterId: master.id,
            value: entry.value,
            field: entry.field,
            parent: entry.parent || entry.fields?.parent || '',
            fields: entry.fields || {},
            key: entry.key,
          }],
        }),
      });
      const data = await response.json().catch(() => ({}));
      if (!response.ok) throw new Error(data.error || `The ${entry.type} could not be mapped.`);
      onSaved(data);
    } catch (err) {
      setError(err.message);
      setBusy(false);
    }
  }

  return (
    <Modal
      title={`Select existing ${entry.type}`}
      onClose={onClose}
      busy={busy}
      footer={<button type="button" className="btn" onClick={onClose} disabled={busy}>Close</button>}
    >
      {error && <div className="flash flash-err">{error}</div>}
      <div className="rounded-lg border border-line bg-[#f7f9fc] px-3 py-2 text-[12px]">
        Workbook value: <strong>{entry.value || '(blank)'}</strong>
        {entry.rows?.length ? <span className="text-inkmuted"> · used on row(s) {entry.rows.slice(0, 20).join(', ')}{entry.rows.length > 20 ? '…' : ''}</span> : null}
        {entry.parent ? <span className="text-inkmuted"> · parent {entry.parent}</span> : null}
      </div>
      <form
        className="mt-3 flex gap-2"
        onSubmit={(event) => { event.preventDefault(); search(); }}
      >
        <input
          className="f-input w-full"
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          placeholder={`Search ${entry.type} by code, name, city or zip`}
          disabled={busy}
        />
        <button type="submit" className="btn" disabled={busy}>
          {busy ? <span className="spin" /> : <LuSearch size={14} />} Search
        </button>
      </form>
      <div className="mt-3 max-h-[48vh] overflow-y-auto rounded-lg border border-line px-3 py-2 text-[12px]">
        {rows.length ? rows.map((master) => (
          <MasterOption key={master.id} master={master} onChoose={choose} busy={busy} />
        )) : (
          <div className="py-4 text-center text-inkmuted">
            {searched ? `No ${entry.type} matched. Search again or close and create it.` : `Search the ${entry.type} master.`}
          </div>
        )}
      </div>
      <div className="mt-2 text-[11.5px] text-inkmuted">
        Choosing a record stores the mapping on this import session. The workbook is revalidated immediately; no
        barcode or stock is written here.
      </div>
    </Modal>
  );
}

